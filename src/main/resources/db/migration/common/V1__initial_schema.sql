-- Hash-chained ledger. Rows are never updated or deleted (enforced by vendor triggers in V2).
CREATE TABLE audit_event (
    seq        BIGINT        PRIMARY KEY,
    action_id  BIGINT        REFERENCES action_proposal (id),
    event      VARCHAR(32)   NOT NULL,
    actor      VARCHAR(300)  NOT NULL,
    detail     VARCHAR(4000) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    prev_hash  CHAR(64)      NOT NULL,
    hash       CHAR(64)      NOT NULL,
    CONSTRAINT uq_audit_event_prev UNIQUE (prev_hash),
    CONSTRAINT uq_audit_event_hash UNIQUE (hash)
);

CREATE INDEX ix_audit_event_action ON audit_event (action_id, seq);

-- Single-row pointer to the newest entry; locked FOR UPDATE to serialize appends.
CREATE TABLE audit_head (
    id   SMALLINT PRIMARY KEY CHECK (id = 1),
    seq  BIGINT   NOT NULL,
    hash CHAR(64) NOT NULL
);


-- Portable DDL (PostgreSQL and H2 in PostgreSQL mode).

CREATE TABLE action_proposal (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agent         VARCHAR(300)  NOT NULL,
    action        VARCHAR(300)  NOT NULL,
    target        VARCHAR(300)  NOT NULL,
    reason        VARCHAR(300)  NOT NULL,
    risk          VARCHAR(16)   NOT NULL CHECK (risk IN ('low', 'medium', 'high', 'critical')),
    status        VARCHAR(16)   NOT NULL
                  CHECK (status IN ('pending', 'approved', 'rejected', 'executed', 'blocked')),
    policy_rule   VARCHAR(64)   NOT NULL,
    policy_detail VARCHAR(4000) NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    reviewed_at   TIMESTAMP WITH TIME ZONE
);

CREATE INDEX ix_action_proposal_status ON action_proposal (status, id);

CREATE TABLE policy_term (
    risk_level VARCHAR(16) NOT NULL CHECK (risk_level IN ('medium', 'high')),
    sort_order INTEGER     NOT NULL,
    term       VARCHAR(40) NOT NULL,
    PRIMARY KEY (risk_level, sort_order),
    CONSTRAINT uq_policy_term UNIQUE (risk_level, term)
);

